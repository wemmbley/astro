<section>
    <h2>Семь чакр в Матрице Судьбы</h2>
    <h3>1. Муладхара (корневая чакра)</h3>
    <p>
        Отвечает за базовую стабильность, выживание, чувство безопасности и связь с физическим миром.
        В матрице отражает способность человека удерживать опору в жизни, строить фундамент, зарабатывать и сохранять ресурс.
    </p>
    <h3>2. Свадхистхана (чувственная чакра)</h3>
    <p>
        Связана с эмоциями, удовольствием, близостью и творческим потоком.
        Показывает, как человек проживает желания, отношения и способность получать удовольствие от жизни.
    </p>
    <h3>3. Манипура (чакра силы)</h3>
    <p>
        Центр воли, самооценки и личной силы.
        В матрице отражает способность действовать, принимать решения, влиять на мир и удерживать внутреннюю позицию.
    </p>
    <h3>4. Анахата (сердечная чакра)</h3>
    <p>
        Отвечает за любовь, принятие, эмпатию и глубокие эмоциональные связи.
        Показывает, насколько человек способен к открытости, отношениям и внутренней гармонии.
    </p>
    <h3>5. Вишудха (горловая чакра)</h3>
    <p>
        Связана с выражением, коммуникацией и самовыражением.
        В матрице показывает способность говорить правду, выражать мысли и проявлять свою индивидуальность через слово.
    </p>
    <h3>6. Аджна (чакра видения)</h3>
    <p>
        Центр интуиции, анализа и внутреннего понимания.
        Отражает способность видеть закономерности, предчувствовать развитие событий и формировать целостное восприятие мира.
    </p>
    <h3>7. Сахасрара (коронная чакра)</h3>
    <p>
        Высший уровень сознания, связь с глобальным смыслом и системой мира.
        В матрице показывает ощущение направления жизни, предназначение и способность видеть жизнь как единый процесс.
    </p>
</section>

